Vocabulary::Vocabulary(int k, string total_file) : k_(k), total_file_(total_file){
    if (total_file_.length() < k_+1)
        throw runtime_error("training text too short, must contain " + to_string(k_+1) + " chars at least, " + to_string(total_file.length()) + " found instead");
}

